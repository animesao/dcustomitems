#!/bin/bash

echo "==========================================="
echo "  DC-CustomItems v1.6.5 Build Script"
echo "==========================================="
echo ""

# Проверяем наличие Maven
if ! command -v mvn &> /dev/null; then
    echo "❌ Maven не найден! Установите Maven для сборки плагина."
    exit 1
fi

echo "🔧 Очистка предыдущих сборок..."
mvn clean

echo ""
echo "📦 Сборка плагина..."
mvn package

if [ $? -eq 0 ]; then
    echo ""
    echo "✅ Плагин успешно собран!"
    echo "📁 Файл находится в: target/CustomItems-1.6.5.jar"
    echo ""
    echo "🎯 Новые возможности v1.6.5:"
    echo "   • Обновлена поддержка Minecraft 1.21.8"
    echo "   • ИСПРАВЛЕНО: Атрибуты теперь корректно применяются к предметам"
    echo "   • Добавлены 10 новых тотемов с эффектами:"
    echo "     - Тотем Огня (Сила III, Скорость II, Огнестойкость, Поглощение)"
    echo "     - Тотем Воды (Регенерация II, Водное дыхание, Скорость плавания)"
    echo "     - Тотем Земли (Сопротивление II, Сила II, Спешка II)"
    echo "     - Тотем Воздуха (Скорость III, Прыгучесть II, Левитация)"
    echo "     - Тотем Тьмы (Сила IV, Невидимость, Ночное зрение)"
    echo "     - Тотем Света (Регенерация III, Прилив здоровья II, Удача)"
    echo "     - Тотем Льда (Сопротивление III, Поглощение III)"
    echo "     - Тотем Грозы (Сила III, Скорость III, Спешка II)"
    echo "     - Тотем Природы (Регенерация II, Прилив здоровья III, Спешка III)"
    echo "   • Все тотемы работают как руны во второй руке"
    echo "   • Добавлены уникальные атрибуты для каждого тотема"
    echo "   • Исправлены deprecated методы для Minecraft 1.21.8"
    echo ""
else
    echo ""
    echo "❌ Ошибка при сборке плагина!"
    exit 1
fi